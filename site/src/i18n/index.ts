const messages: Record<Locale, Dictionary> = {
  en,
  'zh-tw': zhTw,
  'zh-cn': zhCn,
};

export function parseLocale(value: unknown): Locale | null {
  return typeof value === 'string' &&
    (SUPPORTED_LOCALES as readonly string[]).includes(value)
    ? value as Locale
    : null;
}

export function assertLocale(value: unknown): Locale {
  const locale = parseLocale(value);
  if (locale === null) {
    throw new TypeError(`Unsupported locale: ${String(value)}`);
  }
  return locale;
}

function normalizeRoute(route: string): string {
  return route.replace(/^\/+|\/+$/g, '');
}

export function localizedPath(locale: Locale, route = ''): string {
  const rest = normalizeRoute(route);
  return `${SITE_BASE}${locale}/${rest ? `${rest}/` : ''}`;
}

export function routeForLocale(locale: Locale, currentPath: string): string {
  if (!currentPath.startsWith(SITE_BASE)) {
    throw new TypeError(`Path is outside the site base: ${currentPath}`);
  }
  const relative = currentPath.slice(SITE_BASE.length);
  const segments = normalizeRoute(relative).split('/').filter(Boolean);
  if (parseLocale(segments[0])) {
    segments.shift();
  }
  return localizedPath(locale, segments.join('/'));
}

export function t(
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number> = {},
): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match
  );
}

export function statusMessageKey(status: string): MessageKey {
  switch (status) {
    case 'Synced': return 'statusSynced';
    case 'Frozen': return 'statusFrozen';
    case 'Local': return 'statusLocal';
    case 'Restricted': return 'statusRestricted';
    case 'Removed': return 'statusRemoved';
    default: throw new TypeError(`Unsupported status label: ${status}`);
  }
}
